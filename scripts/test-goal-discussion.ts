import assert from 'node:assert/strict';
import {normalizeGoalDiscussion,mergeGoalDiscussion,goalDiscussionContext,validateDiscussionMaterial,assertDiscussionCapacity} from '../src/features/koda/goalDiscussion';
import {normalizeWizardDraft,stageWizardDraft,emptyWizardSyncState,wizardSyncView} from '../src/features/koda/wizardDraftSync';
import {createGoal,normalizeGoal} from '../src/features/koda/goalLogic';
import {mergeGoalEntities} from '../src/features/koda/entitySync';
const a={id:'a',role:'user' as const,content:'Урок 6 уже закончил',at:'2026-11-06T10:00:00Z'};
const b={id:'b',role:'user' as const,content:'В программе ещё 30 уроков',at:'2026-11-06T10:01:00Z'};
const left=normalizeGoalDiscussion({messages:[a],materials:[],removedIds:[]});
const right=normalizeGoalDiscussion({messages:[b],materials:[],removedIds:[]});
const merged=mergeGoalDiscussion(left,right);
assert.equal(merged.messages.length,2);
assert.deepEqual(merged,mergeGoalDiscussion(right,left));
assert.equal(mergeGoalDiscussion({...left,removedIds:['a']},merged).messages.length,1);
assert.equal((normalizeGoalDiscussion({messages:[{...a,secret:'never'}]}).messages[0] as any).secret,undefined);
const goal={...createGoal({title:'Учёба',desiredResult:'Результат',deadline:'',priority:'main'}),assistantDiscussion:merged};
assert.deepEqual(normalizeGoal(goal)?.assistantDiscussion,merged);
assert.equal(mergeGoalEntities({...goal,assistantDiscussion:left},{...goal,assistantDiscussion:right}).assistantDiscussion?.messages.length,2);
const payload=normalizeWizardDraft({version:1,wish:'Учёба',assistantDiscussion:merged})!;
assert.deepEqual(payload.assistantDiscussion,merged);
const owner='00000000-0000-4000-8000-000000000001';
const state=stageWizardDraft(emptyWizardSyncState(owner),payload,'discussion-rev');
assert.deepEqual(wizardSyncView(state).draft?.assistantDiscussion,merged);
assert.throws(()=>validateDiscussionMaterial('course.pdf','text',left));
assert.throws(()=>validateDiscussionMaterial('course.txt','\u0000',left));
validateDiscussionMaterial('course.md','# 30 уроков',left);
assert.throws(()=>assertDiscussionCapacity({...left,messages:Array.from({length:10},(_,i)=>({...a,id:String(i),content:'я'.repeat(4000)}))}));
const huge={...merged,materials:Array.from({length:2000},(_,i)=>({id:String(i),name:'course.txt',content:'quote " '.repeat(10),at:a.at}))};
const context=goalDiscussionContext(huge,'Направление: Python; действие: проверить merge');
assert.equal(JSON.parse(context).currentDraft,'Направление: Python; действие: проверить merge');
assert.ok(context.length<=24000);assert.equal(JSON.parse(context).history.at(-1).text,b.content);
console.log('Goal discussion persistence, concurrent merge, deletion, material validation and bounded context PASS');
