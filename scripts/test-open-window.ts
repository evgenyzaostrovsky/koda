import assert from 'node:assert/strict';
import { createGoal, createGoalAction, normalizeGoal, wouldCreateDependencyCycle } from '../src/features/koda/goalLogic';
import { createOpenWindow, getOpenWindowCells, mergeGoalWindows, updateOpenWindow } from '../src/features/koda/openWindow';
const goal = createGoal({ title: 'Портфолио', desiredResult: 'Три проекта', deadline: '', priority: 'main' });
const base = { ...goal, openWindow: createOpenWindow(goal.id) };
const cells = getOpenWindowCells(base);
assert.equal(cells.length,81);
assert.equal(cells[40].kind,'goal');
assert.equal(cells.filter(c=>c.kind==='action').length,64);
assert.equal(cells.filter(c=>c.kind==='direction').length,16);
for (const direction of base.openWindow.directions) assert.equal(cells.filter(c=>c.kind==='direction'&&c.directionId===direction.id).length,2);
const action = createGoalAction({ title: 'Первый проект' });
const linked = updateOpenWindow({ ...base, actions:[action] },base.openWindow.directions.map((d,i)=>i===0?{...d,title:'Практика',actionIds:[action.id]}:d),'Добавлено действие','2026-10-20T08:00:00Z');
assert.equal(linked.actions.length,1);
assert.equal(getOpenWindowCells(linked).filter(c=>c.kind==='action'&&c.actionId===action.id).length,1);
const moved=updateOpenWindow(linked,linked.openWindow!.directions.map((d,i)=>({...d,actionIds:i===1?[action.id]:[]})),'Перенос','2026-10-20T09:00:00Z');
assert.equal(moved.actions[0].id,action.id);
assert.equal(moved.openWindow!.history.length,2);
const archived=updateOpenWindow(moved,moved.openWindow!.directions.map((d,i)=>i===1?{...d,archivedAt:'2026-10-20T10:00:00Z'}:d),'Архив');
assert.equal(archived.actions.length,1);
const restored=normalizeGoal(JSON.parse(JSON.stringify(archived)))!;
assert.equal(restored.openWindow?.directions[1].actionIds[0],action.id);
assert.equal(restored.openWindow?.history.length,3);
const fork=updateOpenWindow(base,base.openWindow.directions.map((d,i)=>i===0?{...d,title:'Другой вариант'}:d),'Другое устройство','2026-10-20T08:30:00Z');
const merged=mergeGoalWindows(linked,fork);
assert.ok(merged.openWindow!.conflicts!.length>=1);
assert.deepEqual(mergeGoalWindows(linked,fork),mergeGoalWindows(fork,linked));
assert.equal(normalizeGoal(goal)?.openWindow,undefined);
const dependent={...createGoalAction({title:'Второй шаг'}),dependsOn:[action.id]};
assert.equal(wouldCreateDependencyCycle([action,dependent],action.id,[dependent.id]),true);
assert.equal(wouldCreateDependencyCycle([action,dependent],dependent.id,[action.id]),false);
console.log('Open Window64: 81 cells, 64 slots, identity, move, archive, reload, conflicts, legacy passed');
