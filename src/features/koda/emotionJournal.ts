export function parseEmotionEntries(value: unknown): EmotionEntry[] {
  if (!Array.isArray(value)) return [];
  return value.filter((item): item is EmotionEntry => Boolean(item &&
    ['id', 'occurredAt', 'event', 'group', 'emotion', 'action', 'updatedAt'].every(key => typeof item[key] === 'string') &&
    Number.isFinite(Date.parse(item.occurredAt)) && Number.isFinite(Date.parse(item.updatedAt)) &&
    (item.deletedAt === undefined || typeof item.deletedAt === 'string')));
}

export function mergeEmotionEntries(remote: unknown, local: unknown): EmotionEntry[] {
  const entries = new Map<string, EmotionEntry>();
  for (const entry of [...parseEmotionEntries(remote), ...parseEmotionEntries(local)]) {
    const previous = entries.get(entry.id);
    if (!previous || Date.parse(entry.updatedAt) >= Date.parse(previous.updatedAt)) entries.set(entry.id, entry);
  }
  return [...entries.values()].sort((a, b) => Date.parse(b.occurredAt) - Date.parse(a.occurredAt));
}
